#include <stdint.h>
#include <stddef.h>

// Cores padrão FydelisTech OS
#define COR_FUNDO    0xFF1F052F  // #0F051F roxo escuro (formato 0xAARRGGBB)
#define COR_TEXTO    0xFFE0D7FF  // #E0D7FF roxo claro
#define COR_DESTAQUE 0xFF9D4EDD  // #9D4EDD roxo neon

// Framebuffer VGA 32-bit (modo gráfico simples)
volatile uint32_t *fb = (volatile uint32_t*)0xB8000;
static int fb_largura = 800;
static int fb_altura   = 600;

// Desenha retângulo preenchido
static void fb_preenche(int x, int y, int w, int h, uint32_t cor) {
    for (int yy = y; yy < y + h && yy < fb_altura; yy++) {
        for (int xx = x; xx < x + w && xx < fb_largura; xx++) {
            fb[yy * fb_largura + xx] = cor;
        }
    }
}

// Desenha um pixel
static void fb_pixel(int x, int y, uint32_t cor) {
    if (x >= 0 && x < fb_largura && y >= 0 && y < fb_altura) {
        fb[y * fb_largura + x] = cor;
    }
}

// Desenha texto simples (fonte 8x16)
static void fb_texto(int x, int y, const char *str, uint32_t cor) {
    // Fonte mínima — 8x16 pixels por caractere
    static const uint8_t fonte[128][16] = {
        ['F'] = {0x00,0xFE,0x22,0x22,0x22,0xFE,0x20,0x20,0x20,0x20,0x00,0x00,0x00,0x00,0x00,0x00},
        ['y'] = {0x00,0x66,0x66,0x3C,0x18,0x18,0x18,0x18,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
        ['d'] = {0x00,0x7C,0xC6,0xC6,0xC6,0x7C,0x06,0x06,0x06,0x06,0x00,0x00,0x00,0x00,0x00,0x00},
        ['e'] = {0x00,0x00,0x7C,0xC6,0xC6,0xC6,0xFE,0xC0,0xC0,0xC0,0x00,0x00,0x00,0x00,0x00,0x00},
        ['l'] = {0x00,0x00,0xFC,0x30,0x30,0x30,0x30,0x30,0x30,0x30,0x00,0x00,0x00,0x00,0x00,0x00},
        ['i'] = {0x00,0x00,0x78,0x18,0x18,0x18,0x78,0x18,0x18,0x18,0x00,0x00,0x00,0x00,0x00,0x00},
        ['s'] = {0x00,0x00,0x7E,0xC0,0xC0,0x7C,0x06,0x06,0xC6,0x7C,0x00,0x00,0x00,0x00,0x00,0x00},
        ['T'] = {0x00,0x00,0xFC,0x30,0x30,0x30,0x30,0x30,0x30,0x30,0x30,0x00,0x00,0x00,0x00,0x00},
        ['c'] = {0x00,0x00,0x7C,0xC6,0xC0,0xC0,0xC0,0xC6,0x7C,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
        ['h'] = {0x00,0xE0,0x60,0x60,0x60,0x7C,0x66,0x66,0x66,0xE6,0x00,0x00,0x00,0x00,0x00,0x00},
        ['n'] = {0x00,0xC0,0x60,0x60,0x66,0x7E,0x66,0x66,0x66,0xE6,0x00,0x00,0x00,0x00,0x00,0x00},
        ['O'] = {0x00,0x7C,0xC6,0xC6,0xC6,0xC6,0xC6,0xC6,0xC6,0x7C,0x00,0x00,0x00,0x00,0x00,0x00},
        ['S'] = {0x00,0x7E,0xC0,0xC0,0x7C,0x06,0x06,0x06,0xC6,0x7C,0x00,0x00,0x00,0x00,0x00,0x00},
        ['—'] = {0x00,0x00,0x00,0x00,0xFF,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00},
        [':'] = {0x00,0x00,0x00,0x30,0x30,0x00,0x00,0x00,0x30,0x30,0x00,0x00,0x00,0x00,0x00,0x00},
        [' '] = {0}
    };

    for (int c = 0; str[c]; c++) {
        if (str[c] >= 128) { x += 8; continue; }
        const uint8_t *linhas = fonte[(uint8_t)str[c]];
        if (!linhas) { x += 8; continue; }
        for (int yy = 0; yy < 16; yy++) {
            uint8_t linha = linhas[yy];
            for (int xx = 0; xx < 8; xx++) {
                if (linha & (0x80 >> xx)) {
                    fb_pixel(x + xx, y + yy, cor);
                }
            }
        }
        x += 8;
    }
}

// Inicializa modo gráfico VESA 800x600 32-bit
static void vesa_iniciar(void) {
    // ⚠️ Por enquanto usamos modo texto ampliado → depois trocamos por VESA real
    // Limpa com cor de fundo roxo
    fb_preenche(0, 0, fb_largura, fb_altura, COR_FUNDO);
}

void __attribute__((noreturn)) kernel_corpo(void) {
    // 1. Inicializa vídeo
    vesa_iniciar();

    // 2. Desenha interface
    fb_texto(280, 150, "FydelisTech OS", COR_DESTAQUE);
    fb_texto(240, 200, "Modo Grafico Ativado", COR_TEXTO);
    fb_texto(260, 260, "Carregando Interface...", COR_TEXTO);

    // 3. Aqui depois carrega fyd_desktop
    // ...

    __asm__ __volatile__ ("cli; hlt; jmp .");
}

